// ==================== رندر مقالات ====================
let currentCategory = "all";
let currentPage = 1;
const postsPerPage = 6;

function renderBlogPosts() {
    let filteredPosts = blogPosts;
    if (currentCategory !== "all") {
        filteredPosts = blogPosts.filter(post => post.category === currentCategory);
    }

    const startIndex = (currentPage - 1) * postsPerPage;
    const paginatedPosts = filteredPosts.slice(startIndex, startIndex + postsPerPage);

    const grid = document.getElementById('blogGrid');
    if (!grid) return;

    let html = '';
    paginatedPosts.forEach(post => {
        let imgSrc = post.image;
        if (!imgSrc || imgSrc === '') {
            imgSrc = '../assetss/Images/slider-2.jpg';
        }
        html += `
                    <div class="blog-card" data-id="${post.id}">
                        <div class="blog-image">
                            <img src="${imgSrc}" alt="${post.title}" onerror="this.src='../assetss/Images/slider-2.jpg'">
                            <span class="blog-category-tag">${post.categoryName}</span>
                        </div>
                        <div class="blog-info">
                            <div class="blog-meta">
                                <span class="blog-date"><i class="far fa-calendar-alt"></i> ${post.date}</span>
                                <span class="blog-read-time"><i class="far fa-clock"></i> ${post.readTime}</span>
                            </div>
                            <h3>${post.title}</h3>
                            <p>${post.excerpt}</p>
                            <span class="blog-read-more">ادامه مطلب <i class="fas fa-arrow-left"></i></span>
                        </div>
                    </div>
                `;
    });
    grid.innerHTML = html;

    // رویداد کلیک روی کارت‌ها
    document.querySelectorAll('.blog-card').forEach(card => {
        card.addEventListener('click', function (e) {
            const id = this.getAttribute('data-id');
            window.location.href = `blog-detail.html?id=${id}`;
        });
    });

    renderPagination(filteredPosts.length);
}

function renderPagination(totalPosts) {
    const totalPages = Math.ceil(totalPosts / postsPerPage);
    const pagination = document.getElementById('blogPagination');
    if (!pagination) return;

    if (totalPages <= 1) {
        pagination.innerHTML = '';
        return;
    }

    let html = '';
    for (let i = 1; i <= totalPages; i++) {
        html += `<button class="pagination-btn ${i === currentPage ? 'active' : ''}" data-page="${i}">${i}</button>`;
    }
    pagination.innerHTML = html;

    document.querySelectorAll('.pagination-btn').forEach(btn => {
        btn.addEventListener('click', function () {
            currentPage = parseInt(this.getAttribute('data-page'));
            renderBlogPosts();
            window.scrollTo({ top: 0, behavior: 'smooth' });
        });
    });
}

// دسته بندی
document.querySelectorAll('.category-btn').forEach(btn => {
    btn.addEventListener('click', function () {
        document.querySelectorAll('.category-btn').forEach(b => b.classList.remove('active'));
        this.classList.add('active');
        currentCategory = this.getAttribute('data-category');
        currentPage = 1;
        renderBlogPosts();
    });
});

// منوی موبایل
function initMobileMenu() {
    const burger = document.getElementById('burgerMenu');
    const navCollapse = document.getElementById('mainNavbar');
    if (burger && navCollapse) {
        burger.addEventListener('click', () => {
            navCollapse.classList.toggle('show');
        });
    }
}

document.addEventListener('DOMContentLoaded', () => {
    renderBlogPosts();
    initMobileMenu();
});